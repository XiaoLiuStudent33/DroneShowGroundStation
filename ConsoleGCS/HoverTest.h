#pragma once

#include "FlightData.h"

#include <chrono>

//==================================================
// HoverTest
//
// 无人机悬停测试模块
//
// 功能：
// 1. 记录起飞点
// 2. 计算当前漂移
// 3. 统计最大漂移
// 4. 统计悬停时间
//==================================================

class HoverTest
{
public:

    //--------------------------------------------------
    // 开始测试
    //--------------------------------------------------
    void Start(const FlightData& data);

    //--------------------------------------------------
    // 更新测试
    //--------------------------------------------------
    void Update(const FlightData& data);

    //--------------------------------------------------
    // 停止测试
    //--------------------------------------------------
    void Stop(const FlightData& data);

    //--------------------------------------------------
    // 是否正在测试
    //--------------------------------------------------
    bool Running() const;

    //--------------------------------------------------
    // 已运行时间（秒）
    //--------------------------------------------------
    double GetDuration() const;

    //--------------------------------------------------
    // 当前漂移（米）
    //--------------------------------------------------
    double GetDrift() const;

    //--------------------------------------------------
    // 最大漂移（米）
    //--------------------------------------------------
    double GetMaxDrift() const;

private:

    //--------------------------------------------------
    // 是否正在测试
    //--------------------------------------------------
    bool running = false;

    //--------------------------------------------------
    // 开始时间
    //--------------------------------------------------
    std::chrono::steady_clock::time_point startTime;

    //--------------------------------------------------
    // 起始GPS
    //--------------------------------------------------
    double startLat = 0.0;
    double startLon = 0.0;
    double startAlt = 0.0;

    //--------------------------------------------------
    // 当前漂移（米）
    //--------------------------------------------------
    double currentDrift = 0.0;

    //--------------------------------------------------
    // 最大漂移（米）
    //--------------------------------------------------
    double maxDrift = 0.0;

    //--------------------------------------------------
    // 高度统计
    //--------------------------------------------------
    double maxAlt = -999.0;
    double minAlt = 999.0;

    //--------------------------------------------------
    // 姿态统计
    //--------------------------------------------------
    double maxRoll = 0.0;
    double maxPitch = 0.0;

    //--------------------------------------------------
    // 电池统计
    //--------------------------------------------------
    int startBattery = 0;
    int endBattery = 0;
};